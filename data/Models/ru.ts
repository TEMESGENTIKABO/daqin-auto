export const formatPrice = (priceUSD: number): string => {
  if (priceUSD === 0) {
    return "Цена договорная";
  }
  return `$${priceUSD.toLocaleString()}`;
};

export const isNegotiablePrice = (priceUSD: number): boolean => {
  return priceUSD === 0;
};

export const getModelsByPriceType = (
  type: "fixed" | "negotiable",
): VehicleModel[] => {
  if (type === "negotiable") {
    return vehicleModels.filter((model) => model.priceUSD === 0);
  }
  // Поскольку все цены теперь договорные, возвращаем пустой массив для фиксированных цен
  return [];
};

// Вспомогательная функция для получения моделей с договорными ценами (все модели теперь)
export const getNegotiableModels = (): VehicleModel[] => {
  return vehicleModels.filter((model) => model.priceUSD === 0);
};

// Вспомогательная функция для получения рекомендуемых моделей (для демонстрации на главной странице)
export const getFeaturedModels = (limit?: number): VehicleModel[] => {
  const featured = vehicleModels.filter((model) => model.featured);
  return limit ? featured.slice(0, limit) : featured;
};


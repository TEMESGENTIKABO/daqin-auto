export const getModelById = (id: string): VehicleModel | undefined => {
  return vehicleModels.find((model) => model.id === id);
};

// Вспомогательная функция для получения похожих моделей (по категории или бренду)
export const getSimilarModels = (
  currentModel: VehicleModel,
  limit: number = 4,
): VehicleModel[] => {
  return vehicleModels
    .filter(
      (model) =>
        model.id !== currentModel.id &&
        (model.category === currentModel.category ||
          model.brand === currentModel.brand),
    )
    .slice(0, limit);
};


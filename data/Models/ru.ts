// Обновленная вспомогательная функция для получения моделей с лучшим соотношением цены и качества (все цены договорные теперь)
export const getBestValueModels = (limit: number = 4): VehicleModel[] => {
  // Возвращаем рекомендуемые модели или модели с высоким рейтингом
  return vehicleModels
    .filter((model) => model.rating && model.rating >= 4.0)
    .sort((a, b) => (b.rating || 0) - (a.rating || 0))
    .slice(0, limit);
};


// Вспомогательная функция для получения моделей по категории
export const getModelsByCategory = (category: string): VehicleModel[] => {
  if (category === "all") return vehicleModels;
  if (category === "commercial") {
    return vehicleModels.filter(
      (model) => model.category === "Коммерческий" || model.category === "Пикап",
    );
  }
  return vehicleModels.filter(
    (model) => model.category.toLowerCase() === category.toLowerCase(),
  );
};

